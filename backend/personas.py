def build_system_prompt(persona: dict) -> str:
    """构建完整的系统提示词"""
    prompt = f"""角色背景：
{persona['background']}

性格特点：
{persona['personality']}

说话风格：
{persona['speaking_style']}

专业领域：{', '.join(persona['expertise'])}

请始终保持你扮演的角色特点，用符合该人物风格的方式回答问题。
"""
    return prompt


def get_all_personas() -> list:
    """获取所有人物角色"""
    return PERSONAS


def get_persona_summary() -> list:
    """获取人物简要信息（用于选择列表）"""
    return [
        {
            "id": p["id"],
            "name": p["name"],
            "description": p["description"]
        }
        for p in PERSONAS
    ]
