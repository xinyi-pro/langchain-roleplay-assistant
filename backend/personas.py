def build_system_prompt(persona: dict) -> str:
    """构建完整的系统提示词"""
    prompt = f"""角色背景：
{persona['background']}

性格特点：
{persona['personality']}

说话风格：
{persona['speaking_style']}

专业领域：{', '.join(persona['expertise'])}

请始终保持你扮演的角色特点，用符合该人物风格的方式回答问题。
"""
    return prompt


